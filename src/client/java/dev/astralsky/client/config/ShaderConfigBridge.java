package dev.astralsky.client.config;

import dev.astralsky.client.AstralSkyClient;
import net.fabricmc.loader.api.FabricLoader;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.FileSystem;
import java.nio.file.FileSystems;
import java.nio.file.Files;
import java.nio.file.InvalidPathException;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.nio.file.StandardOpenOption;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Properties;
import java.util.Set;

public final class ShaderConfigBridge {
    private static final List<String> DEVELOPMENT_PACKS = List.of(
        "SunRShader-AstralSky"
    );
    private static final String IDENTITY_INCLUDE = "shaders/lib/astro_config.glsl";
    private static final String RUNTIME_INCLUDE = "shaders/lib/astro_runtime_config.glsl";

    private ShaderConfigBridge() {
    }

    public static void sync(AstralSkyConfig config) {
        Path gameDirectory = FabricLoader.getInstance().getGameDir().toAbsolutePath().normalize();
        Path shaderpacksDirectory = gameDirectory.resolve("shaderpacks").normalize();

        Set<String> candidates = new LinkedHashSet<>();
        readSelectedPack(gameDirectory).ifPresent(candidates::add);
        candidates.addAll(DEVELOPMENT_PACKS);

        boolean wroteAnyPack = false;
        for (String candidate : candidates) {
            Path packPath = safePackPath(shaderpacksDirectory, candidate);
            if (packPath == null) {
                continue;
            }

            try {
                if (syncPack(packPath, render(config.validated()))) {
                    AstralSkyClient.LOGGER.info("Synced shader configuration to {}", packPath);
                    wroteAnyPack = true;
                }
            } catch (IOException exception) {
                AstralSkyClient.LOGGER.error("Unable to update {}", packPath, exception);
            }
        }

        if (!wroteAnyPack) {
            AstralSkyClient.LOGGER.warn(
                "No unpacked AstralSky shader pack was found in {}; shader configuration was not synced",
                shaderpacksDirectory
            );
        }
    }

    /**
     * Bump whenever the generated option mapping (time-mode numbers, field
     * semantics) changes meaning. The pack's lib/astro_config.glsl ignores a
     * runtime configuration whose schema differs, so a companion and a pack
     * built from different generations can never silently misread each other.
     */
    static final int RUNTIME_CONFIG_SCHEMA = 3;

    static String render(AstralSkyConfig config) {
        int timeMode = switch (config.timeMode()) {
            case SYSTEM_REALTIME -> 0;
            case FIXED_DATETIME -> 1;
            case FIXED_START_GAME_ELAPSED -> 2;
        };

        return String.format(
            Locale.ROOT,
            """
                // Generated by the AstralSky Fabric companion. Edit config/astralsky.json instead.
                #define ASTRO_RUNTIME_CONFIG 1
                #define ASTRO_CFG_SCHEMA %d
                #define ASTRO_CFG_TIME_MODE %d
                #define ASTRO_CFG_LATITUDE %.8f
                #define ASTRO_CFG_LONGITUDE %.8f
                #define ASTRO_CFG_UTC_OFFSET %.8f
                #define ASTRO_CFG_FIXED_YEAR %d
                #define ASTRO_CFG_FIXED_MONTH %d
                #define ASTRO_CFG_FIXED_DAY %d
                #define ASTRO_CFG_FIXED_HOUR %.8f
                #define ASTRO_CFG_NORTH_OFFSET %.8f
                #define ASTRO_CFG_ADVANCING_START_DAY %d
                #define ASTRO_CFG_ADVANCING_START_TIME %d
                """,
            RUNTIME_CONFIG_SCHEMA,
            timeMode,
            config.latitudeDegrees(),
            config.longitudeDegreesEast(),
            config.utcOffsetHours(),
            config.fixedYear(),
            config.fixedMonth(),
            config.fixedDay(),
            config.fixedLocalHour(),
            config.northOffsetDegrees(),
            config.advancingStartWorldDay(),
            config.advancingStartWorldTime()
        );
    }

    private static java.util.Optional<String> readSelectedPack(Path gameDirectory) {
        Path irisProperties = gameDirectory.resolve("config/iris.properties");
        if (!Files.isRegularFile(irisProperties)) {
            return java.util.Optional.empty();
        }

        Properties properties = new Properties();
        try (var reader = Files.newBufferedReader(irisProperties, StandardCharsets.UTF_8)) {
            properties.load(reader);
        } catch (IOException exception) {
            AstralSkyClient.LOGGER.warn("Unable to read Iris configuration from {}", irisProperties, exception);
            return java.util.Optional.empty();
        }

        String selected = properties.getProperty("shaderPack", "").trim();
        return selected.isEmpty() ? java.util.Optional.empty() : java.util.Optional.of(selected);
    }

    private static Path safePackPath(Path shaderpacksDirectory, String packName) {
        final Path relative;
        try {
            relative = Path.of(packName);
        } catch (InvalidPathException exception) {
            return null;
        }

        if (packName.isBlank() || relative.isAbsolute() || relative.getNameCount() != 1) {
            return null;
        }

        Path resolved = shaderpacksDirectory.resolve(relative).normalize();
        return resolved.getParent() != null && resolved.getParent().equals(shaderpacksDirectory)
            ? resolved
            : null;
    }

    static boolean syncPack(Path packPath, String content) throws IOException {
        if (Files.isDirectory(packPath)) {
            Path identityFile = packPath.resolve(IDENTITY_INCLUDE);
            if (!Files.isRegularFile(identityFile)) {
                return false;
            }
            writeIfChanged(packPath.resolve(RUNTIME_INCLUDE), content);
            return true;
        }

        if (!Files.isRegularFile(packPath)
            || !packPath.getFileName().toString().toLowerCase(Locale.ROOT).endsWith(".zip")) {
            return false;
        }

        try (FileSystem archive = FileSystems.newFileSystem(packPath, Map.of())) {
            Path identityFile = archive.getPath("/" + IDENTITY_INCLUDE);
            if (!Files.isRegularFile(identityFile)) {
                return false;
            }
            Path runtimeInclude = archive.getPath("/" + RUNTIME_INCLUDE);
            writeArchiveIfChanged(runtimeInclude, content);
            return true;
        }
    }

    private static void writeArchiveIfChanged(Path destination, String content) throws IOException {
        if (Files.isRegularFile(destination)
            && Files.readString(destination, StandardCharsets.UTF_8).equals(content)) {
            return;
        }
        Files.createDirectories(destination.getParent());
        Files.writeString(
            destination,
            content,
            StandardCharsets.UTF_8,
            StandardOpenOption.CREATE,
            StandardOpenOption.TRUNCATE_EXISTING
        );
    }

    private static void writeIfChanged(Path destination, String content) throws IOException {
        if (Files.isRegularFile(destination)
            && Files.readString(destination, StandardCharsets.UTF_8).equals(content)) {
            return;
        }

        Files.createDirectories(destination.getParent());
        Path temporary = Files.createTempFile(destination.getParent(), "astralsky-runtime-", ".glsl.tmp");
        try {
            Files.writeString(temporary, content, StandardCharsets.UTF_8);
            try {
                Files.move(
                    temporary,
                    destination,
                    StandardCopyOption.ATOMIC_MOVE,
                    StandardCopyOption.REPLACE_EXISTING
                );
            } catch (AtomicMoveNotSupportedException exception) {
                Files.move(temporary, destination, StandardCopyOption.REPLACE_EXISTING);
            }
        } finally {
            Files.deleteIfExists(temporary);
        }
    }
}
