import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Converts the committed VSOP87D series in {@code tools/vsop87d} into the
 * amplitude-truncated coefficient tables used by the Java reference
 * implementation and by the shader pack.
 *
 * <p>Both outputs are generated from the same truncation so that the Java
 * implementation and the GLSL implementation stay term-for-term identical.
 * Truncation is by amplitude, which bounds the dropped contribution by the sum
 * of the dropped amplitudes; the measured geocentric error stays below two
 * arcseconds between 2000 and 2050.
 */
public final class Vsop87Generator {
    /**
     * Order matters: the shader dispatcher and {@link #BODY_IDS} use these
     * indices, and Earth is last so the seven visible planets can be looped
     * over directly.
     */
    private static final List<String> BODY_IDS = List.of(
        "mercury", "venus", "mars", "jupiter", "saturn", "uranus", "neptune", "earth"
    );

    // Amplitudes are stored in units of 1e-8 rad (1e-8 AU for R). Earth needs a
    // finer cutoff because its position error is common to every geocentric
    // planet direction.
    private static final double ANGLE_CUTOFF = 3.0e-7;
    private static final double EARTH_ANGLE_CUTOFF = 1.0e-7;
    private static final double RADIUS_CUTOFF = 1.0e-6;

    private static final String[] COORDINATES = {"L", "B", "R"};
    private static final int MAX_POWER = 6;

    private record Term(double amplitude, double phase, double frequency, int power) {
    }

    private Vsop87Generator() {
    }

    public static void main(String[] args) throws IOException {
        if (args.length != 3) {
            throw new IllegalArgumentException(
                "Usage: Vsop87Generator <data directory> <Java output> <GLSL output>"
            );
        }

        Path dataDirectory = Path.of(args[0]);
        Path javaOutput = Path.of(args[1]);
        Path glslOutput = Path.of(args[2]);

        List<Map<String, List<Term>>> bodies = new ArrayList<>();
        for (String id : BODY_IDS) {
            bodies.add(readBody(dataDirectory.resolve(id + ".csv"), id));
        }

        writeJava(javaOutput, bodies);
        writeGlsl(glslOutput, bodies);

        int total = bodies.stream()
            .flatMap(body -> body.values().stream())
            .mapToInt(List::size)
            .sum();
        System.out.println("VSOP87: " + total + " terms written to " + javaOutput
            + " and " + glslOutput);
    }

    private static Map<String, List<Term>> readBody(Path file, String id) throws IOException {
        Map<String, List<Term>> series = new LinkedHashMap<>();
        for (String coordinate : COORDINATES) {
            series.put(coordinate, new ArrayList<>());
        }

        for (String line : Files.readAllLines(file, StandardCharsets.UTF_8)) {
            if (line.isBlank()) {
                continue;
            }
            String[] fields = line.trim().split("\\s+");
            String header = fields[0];
            String coordinate = header.substring(0, 1);
            int power = Integer.parseInt(header.substring(1));
            double amplitude = Double.parseDouble(fields[1]) * 1e-8;
            double phase = Double.parseDouble(fields[2]);
            double frequency = Double.parseDouble(fields[3]);

            double cutoff = coordinate.equals("R")
                ? RADIUS_CUTOFF
                : (id.equals("earth") ? EARTH_ANGLE_CUTOFF : ANGLE_CUTOFF);
            if (Math.abs(amplitude) < cutoff) {
                continue;
            }
            series.get(coordinate).add(new Term(amplitude, phase, frequency, power));
        }
        return series;
    }

    private static void writeJava(Path output, List<Map<String, List<Term>>> bodies)
        throws IOException {
        StringBuilder source = new StringBuilder();
        source.append("package dev.astralsky.astro;\n\n");
        source.append("/**\n");
        source.append(" * Amplitude-truncated VSOP87D coefficient tables, generated by\n");
        source.append(" * tools/Vsop87Generator.java from tools/vsop87d. Do not edit.\n");
        source.append(" *\n");
        source.append(" * <p>Heliocentric spherical coordinates referred to the mean ecliptic and\n");
        source.append(" * equinox of date. Each coordinate stores flat (amplitude, phase, frequency)\n");
        source.append(" * triples grouped by the power of the Julian-millennia argument; the counts\n");
        source.append(" * array holds the number of terms for each power from 0 to 5.\n");
        source.append(" */\n");
        source.append("public final class Vsop87Tables {\n");
        source.append("    private Vsop87Tables() {\n");
        source.append("    }\n\n");

        int total = bodies.stream().flatMap(b -> b.values().stream()).mapToInt(List::size).sum();
        source.append("    public static final int TOTAL_TERMS = ").append(total).append(";\n\n");

        List<String> constants = new ArrayList<>();
        for (int index = 0; index < bodies.size(); index++) {
            String id = BODY_IDS.get(index);
            Map<String, List<Term>> series = bodies.get(index);
            source.append("    public static final BodyData ")
                .append(id.toUpperCase(Locale.ROOT))
                .append(" = new BodyData(\n");
            source.append("        \"").append(id).append("\",\n");
            appendJavaCoordinate(source, series.get("L"), false);
            appendJavaCoordinate(source, series.get("B"), false);
            appendJavaCoordinate(source, series.get("R"), true);
            source.append("    );\n\n");
            constants.add(id.toUpperCase(Locale.ROOT));
        }

        source.append("    public static final BodyData[] BODIES = { ")
            .append(String.join(", ", constants))
            .append(" };\n\n");

        source.append("    public static final int EARTH_INDEX = ")
            .append(BODY_IDS.indexOf("earth"))
            .append(";\n\n");

        source.append(indent(4, """
            public static final class BodyData {
                public final String id;
                public final double[] longitude;
                public final int[] longitudeCounts;
                public final double[] latitude;
                public final int[] latitudeCounts;
                public final double[] radius;
                public final int[] radiusCounts;

                private BodyData(
                    String id,
                    double[] longitude,
                    int[] longitudeCounts,
                    double[] latitude,
                    int[] latitudeCounts,
                    double[] radius,
                    int[] radiusCounts
                ) {
                    this.id = id;
                    this.longitude = longitude;
                    this.longitudeCounts = longitudeCounts;
                    this.latitude = latitude;
                    this.latitudeCounts = latitudeCounts;
                    this.radius = radius;
                    this.radiusCounts = radiusCounts;
                }

                public int termCount() {
                    int total = 0;
                    for (int count : longitudeCounts) {
                        total += count;
                    }
                    for (int count : latitudeCounts) {
                        total += count;
                    }
                    for (int count : radiusCounts) {
                        total += count;
                    }
                    return total;
                }
            }
            """));
        source.append("}\n");

        Files.createDirectories(output.getParent());
        Files.writeString(output, source.toString(), StandardCharsets.UTF_8);
    }

    private static void appendJavaCoordinate(
        StringBuilder source, List<Term> terms, boolean last
    ) {
        int[] counts = new int[MAX_POWER];
        for (Term term : terms) {
            counts[term.power()]++;
        }

        source.append("        new double[] {\n");
        StringBuilder line = new StringBuilder("            ");
        int column = 0;
        for (Term term : terms) {
            String value = Double.toString(term.amplitude()) + ", "
                + Double.toString(term.phase()) + ", "
                + Double.toString(term.frequency()) + ", ";
            if (column >= 3) {
                source.append(line).append('\n');
                line.setLength(0);
                line.append("            ");
                column = 0;
            }
            line.append(value);
            column++;
        }
        if (line.length() > 12) {
            source.append(line).append('\n');
        }
        source.append("        },\n");

        source.append("        new int[] { ");
        for (int power = 0; power < MAX_POWER; power++) {
            if (power > 0) {
                source.append(", ");
            }
            source.append(counts[power]);
        }
        source.append(last ? " }\n" : " },\n");
    }

    /** Indents every non-empty line so the nested class sits inside its parent. */
    private static String indent(int spaces, String text) {
        String prefix = " ".repeat(spaces);
        StringBuilder result = new StringBuilder();
        for (String line : text.lines().toList()) {
            if (!line.isEmpty()) {
                result.append(prefix);
            }
            result.append(line).append('\n');
        }
        return result.toString();
    }

    private static void writeGlsl(Path output, List<Map<String, List<Term>>> bodies)
        throws IOException {
        StringBuilder source = new StringBuilder();
        source.append("// Generated by tools/Vsop87Generator.java from tools/vsop87d. Do not edit.\n");
        source.append("// Amplitude-truncated VSOP87D heliocentric series; see docs/PLANETS.md.\n");
        source.append("#if !defined INCLUDE_SKY_VSOP87\n");
        source.append("#define INCLUDE_SKY_VSOP87\n\n");

        for (int index = 0; index < bodies.size(); index++) {
            String id = BODY_IDS.get(index);
            String upper = id.toUpperCase(Locale.ROOT);
            Map<String, List<Term>> series = bodies.get(index);

            for (String coordinate : COORDINATES) {
                List<Term> terms = series.get(coordinate);
                source.append("const int VSOP_").append(upper).append('_').append(coordinate)
                    .append("_N = ").append(terms.size()).append(";\n");
                source.append("const vec4 VSOP_").append(upper).append('_').append(coordinate)
                    .append("[VSOP_").append(upper).append('_').append(coordinate)
                    .append("_N] = vec4[](\n");
                for (int termIndex = 0; termIndex < terms.size(); termIndex++) {
                    Term term = terms.get(termIndex);
                    source.append("    vec4(")
                        .append(formatFloat(term.amplitude())).append(", ")
                        .append(formatFloat(term.phase())).append(", ")
                        .append(formatFloat(term.frequency())).append(", ")
                        .append(term.power()).append(".0)")
                        .append(termIndex + 1 < terms.size() ? ",\n" : "\n");
                }
                source.append(");\n\n");
            }

            source.append("void vsop87_").append(id).append("(float t, out vec3 spherical) {\n");
            source.append("    float power[6] = float[](\n");
            source.append("        1.0, t, t * t, t * t * t, t * t * t * t, t * t * t * t * t\n");
            source.append("    );\n");
            appendGlslCoordinate(source, upper, "L", "longitude");
            appendGlslCoordinate(source, upper, "B", "latitude");
            appendGlslCoordinate(source, upper, "R", "distance");
            source.append("    spherical = vec3(longitude, latitude, distance);\n");
            source.append("}\n\n");
        }

        source.append("// Bodies follow the order of Vsop87.Body: Mercury, Venus, Mars,\n");
        source.append("// Jupiter, Saturn, Uranus, Neptune, Earth.\n");
        source.append("vec3 vsop87_heliocentric(int body, float t) {\n");
        source.append("    vec3 spherical = vec3(0.0, 0.0, 1.0);\n");
        for (int index = 0; index < bodies.size(); index++) {
            String id = BODY_IDS.get(index);
            source.append("    ").append(index == 0 ? "if" : "else if")
                .append(" (body == ").append(index).append(") {\n");
            source.append("        vsop87_").append(id).append("(t, spherical);\n");
            source.append("    }\n");
        }
        source.append("    return spherical;\n");
        source.append("}\n\n");
        source.append("#endif // INCLUDE_SKY_VSOP87\n");

        Files.createDirectories(output.getParent());
        Files.writeString(output, source.toString(), StandardCharsets.UTF_8);
    }

    private static void appendGlslCoordinate(
        StringBuilder source, String upper, String coordinate, String variable
    ) {
        String array = "VSOP_" + upper + "_" + coordinate;
        source.append("    float ").append(variable).append(" = 0.0;\n");
        source.append("    for (int i = 0; i < ").append(array).append("_N; ++i) {\n");
        source.append("        vec4 term = ").append(array).append("[i];\n");
        source.append("        ").append(variable)
            .append(" += term.x * cos(term.y + term.z * t) * power[int(term.w)];\n");
        source.append("    }\n");
    }

    private static String formatFloat(double value) {
        return String.format(Locale.ROOT, "%.9e", value);
    }
}
